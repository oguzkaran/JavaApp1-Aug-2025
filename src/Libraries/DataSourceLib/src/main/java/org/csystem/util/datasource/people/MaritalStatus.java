package org.csystem.util.datasource.people;

/**
 * Represents the marital status of a person.
 */
public enum MaritalStatus {
    /** The person is single (never married). */
    SINGLE,
    /** The person is currently married. */
    MARRIED,
    /** The person is divorced. */
    DIVORCED,
    /** The person is widowed. */
    WIDOW
}
